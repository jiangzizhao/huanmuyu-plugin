def katakana_to_hiragana(text: str) -> str:
    return "".join(
        chr(ord(char) - 0x60) if "ァ" <= char <= "ヶ" else char
        for char in text
    )


def annotate_token(surface: str, reading: str) -> str:
    """Put ruby only on kanji runs, leaving okurigana such as 食べ plain."""
    if not KANJI_RE.search(surface):
        return surface
    reading = katakana_to_hiragana(reading)
    parts = [part for part in KANJI_RUN_RE.split(surface) if part]
    output: list[str] = []
    cursor = 0
    for index, part in enumerate(parts):
        if not KANJI_RUN_RE.fullmatch(part):
            output.append(part)
            normalized = katakana_to_hiragana(part)
            if reading.startswith(normalized, cursor):
                cursor += len(normalized)
            continue

        next_kana = next(
            (
                katakana_to_hiragana(candidate)
                for candidate in parts[index + 1 :]
                if not KANJI_RUN_RE.fullmatch(candidate)
            ),
            "",
        )
        # Okurigana usually matches the final occurrence in the reading
        # (聞き=きき, 奪う=うばう), so align from the right.
        end = reading.rfind(next_kana, cursor) if next_kana else len(reading)
        if end < cursor:
            end = len(reading)
        ruby = reading[cursor:end]
        output.append(f"{{{part}|{ruby}}}" if ruby else part)
        cursor = end
    return "".join(output)


def annotate_segment(text: str) -> str:
    """Annotate a segment that contains no manual phrase overrides."""
    output: list[str] = []
    for token in TAGGER(text):
        surface = token.surface
        reading = token.feature[7] if len(token.feature) > 7 else ""
        if KANJI_RE.search(surface) and reading and reading != "*":
            output.append(annotate_token(surface, reading))
        else:
            output.append(surface)
    return "".join(output)


def add_furigana(text: str) -> str:
    """Annotate every kanji run as {base|hiragana}, with contextual overrides."""
    output: list[str] = []
    last = 0
    for match in PHRASE_RE.finditer(text):
        output.append(annotate_segment(text[last : match.start()]))
        phrase = match.group(0)
        output.append(PHRASE_ANNOTATIONS[phrase])
        last = match.end()
    output.append(annotate_segment(text[last:]))
    return "".join(output)


