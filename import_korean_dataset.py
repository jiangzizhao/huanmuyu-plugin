#!/usr/bin/env python3
"""Build Huanmuyu's six Korean proficiency bands from an open learning dataset.

The source's six ordered volumes are used as TOPIK-oriented ability bands. The
result is not represented as an official NIIED vocabulary list. Duplicate terms
are kept at the earliest band so learners do not receive the same word twice.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent
WORDLIST_DIR = ROOT / "wordlists"
LEVELS = [f"TOPIK {number}" for number in range(1, 7)]


def load_rows(source: Path, volume: int) -> list[dict]:
    payload = json.loads((source / "data" / "json" / f"vol-{volume:02d}.json").read_text(encoding="utf-8"))
    rows = payload.get("rows", [])
    if not isinstance(rows, list):
        raise ValueError(f"volume {volume} has invalid rows")
    return [row for row in rows if isinstance(row, dict)]


def clean_term(raw: object) -> str:
    value = re.sub(r"\s+", " ", str(raw or "").strip())
    if not re.search(r"[가-힣]", value) or len(value) > 40:
        return ""
    return value


def ts_string(value: object) -> str:
    return json.dumps(str(value or ""), ensure_ascii=False)


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: import_korean_dataset.py /path/to/yonsei-korean-vocabulary")
    source = Path(sys.argv[1]).resolve()
    if not (source / "LICENSE.md").exists():
        raise SystemExit("source repository not found")

    used: set[str] = set()
    cards: dict[str, dict[str, str]] = {}
    counts: dict[str, int] = {}
    for volume, level in enumerate(LEVELS, start=1):
        words: list[str] = []
        for row in load_rows(source, volume):
            word = clean_term(row.get("korean"))
            if not word or word in used:
                continue
            used.add(word)
            words.append(word)
            card: dict[str, str] = {}
            translation = str(row.get("chinese") or "").strip()
            pronunciation = str(row.get("pronunciation") or "").strip()
            if translation:
                card["翻译"] = translation
            if pronunciation:
                card["ipa"] = pronunciation
            if card:
                cards[word] = card
        (WORDLIST_DIR / f"{level}.json").write_text(
            json.dumps(words, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        counts[level] = len(words)

    # Rebuild the complete embedded wordlist map because Obsidian community
    # releases only install main.js/manifest/styles.css.
    wordlist_files = sorted(WORDLIST_DIR.glob("*.json"), key=lambda p: p.name)
    wordlists: dict[str, list[str]] = {}
    for path in wordlist_files:
        if path.name == "index.json":
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(data, list):
            wordlists[path.stem] = [str(item) for item in data]
    (WORDLIST_DIR / "index.json").write_text(
        json.dumps({key: len(value) for key, value in wordlists.items()}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    (ROOT / "wordlists.ts").write_text(
        "// Generated by import_korean_dataset.py. Do not edit by hand.\n"
        "export const WORDLISTS: Record<string, string[]> = "
        + json.dumps(wordlists, ensure_ascii=False, separators=(",", ":"))
        + ";\n",
        encoding="utf-8",
    )
    (ROOT / "korean-cards.ts").write_text(
        "// Korean vocabulary data adapted from Open Yonsei Korean Vocabulary v0.1.0, CC BY-SA 3.0.\n"
        "// Re-grouped as TOPIK-oriented ability bands; not an official NIIED word list.\n"
        "export const KOREAN_CARDS: Record<string, { ipa?: string; 翻译?: string }> = "
        + json.dumps(cards, ensure_ascii=False, separators=(",", ":"))
        + ";\n",
        encoding="utf-8",
    )
    print(json.dumps({"levels": counts, "total": len(used), "cards": len(cards)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
